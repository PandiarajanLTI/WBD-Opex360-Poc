from typing import Protocol, Any
from app.schemas.grid import GridQuery
class ForecastRepository(Protocol):
    def list_templates(self) -> list[dict[str, Any]]: ...
    def create_templates(self, templates: list[dict[str, Any]]) -> list[dict[str, Any]]: ...
    def metadata(self, template_name: str) -> dict[str, Any]: ...
    def query(self, template_name: str, request: GridQuery) -> tuple[list[dict[str, Any]], int]: ...
    def summarize(self, template_name: str, request: GridQuery) -> tuple[list[dict[str, Any]], int]: ...
    def save(self, template_name: str, rows: list[dict[str, Any]]) -> int: ...
    def valid_combination(self, company_code: str, cost_center: str, profit_center: str) -> bool: ...
    def budget_query(self, request: GridQuery) -> tuple[list[dict[str, Any]], int]: ...
    def budget_save(self, rows: list[dict[str, Any]]) -> int: ...
